#!/usr/bin/env python3
"""Refresh the skill files embedded in the newest CHANGELOG upgrade prompt.

Enterprise users without network or install access upgrade by pasting that
prompt into Claude Code, so it must carry every skill file verbatim. Run this
after any change under skills/code-better/. `--check` exits 1 when the embedded
copy is stale (tests/test_upgrade_prompt.py runs it in CI). Stdlib only.
"""
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "code-better"
CHANGELOG = ROOT / "CHANGELOG.md"
FILES = ["SKILL.md", "references/templates.md", "references/code-map.md",
         "references/review.md", "hooks/guard.py", "hooks/settings.json"]
START = "=== FILES (generated by scripts/upgrade_prompt.py; do not edit by hand) ==="
FENCE = "`````"  # five backticks: the embedded files contain three-backtick fences


def payload():
    texts = {f: (SKILL / f).read_text(encoding="utf-8") for f in FILES}
    for f, text in texts.items():
        if FENCE in text or "=== END " in text:
            raise SystemExit("%s contains a prompt delimiter; change FENCE or the markers" % f)
    out = ["Checksums (shasum -a 256 output, run from TARGET):"]
    out += ["%s  %s" % (hashlib.sha256(t.encode("utf-8")).hexdigest(), f) for f, t in texts.items()]
    for f, text in texts.items():
        out += ["", "=== BEGIN %s ===" % f, text + "=== END %s ===" % f]
    return "\n".join(out) + "\n"


def render(changelog):
    """Return the changelog with the first (newest) payload region regenerated."""
    head, sep, rest = changelog.partition(START + "\n")
    if not sep:
        raise SystemExit("marker not found in CHANGELOG.md: " + START)
    if head.count("\n## [") != 1:  # never refresh an older release's prompt with newer files
        raise SystemExit("the newest CHANGELOG release has no upgrade prompt: copy the last one under it first")
    end = ("\n" + rest).find("\n" + FENCE + "\n")  # index of the fence line within rest
    if end < 0:
        raise SystemExit("closing %s fence not found after the marker" % FENCE)
    return head + sep + payload() + rest[end:]


def main(argv):
    current = CHANGELOG.read_text(encoding="utf-8")
    fresh = render(current)
    if "--check" in argv:
        if fresh != current:
            print("CHANGELOG.md upgrade prompt is stale: run python3 scripts/upgrade_prompt.py", file=sys.stderr)
            return 1
        return 0
    if fresh != current:
        CHANGELOG.write_text(fresh, encoding="utf-8")
    print("CHANGELOG.md upgrade prompt: %s" % ("updated" if fresh != current else "already fresh"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
